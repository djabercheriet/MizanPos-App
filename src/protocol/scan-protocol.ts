/**
 * MIZANE Mobile Scanner — Scan Protocol (v1) — client mirror.
 *
 * This is a faithful TypeScript mirror of the desktop module
 * `KINETIC_POS/electron/scan-protocol.js`. It reproduces the exact constants,
 * regexes, message shapes, reason codes and acknowledgement semantics so the
 * phone is WIRE-COMPATIBLE with the existing Phase 1 gateway.
 *
 * It is transport-independent: nothing here knows about sockets, TLS or
 * React Native. The direction of travel mirrored here is CLIENT → DESKTOP for
 * the messages we build, and DESKTOP → CLIENT for the messages we parse.
 *
 * Do NOT change any literal in this file without a matching change on the
 * desktop side (the desktop rejects version/type/format mismatches outright).
 */

/** Wire version. A mismatch is rejected outright by the gateway. */
export const PROTOCOL_VERSION = 1;

/** Marker used inside the pairing QR so a scan target can be identified. */
export const PROTOCOL_MARKER = 'mizane-scan';

/** Hard ceiling for a single frame, in UTF-8 bytes. */
export const MAX_FRAME_BYTES = 4096;

/** Barcode constraints (mirrors the desktop exactly). */
export const MAX_BARCODE_LENGTH = 64;
export const MIN_BARCODE_LENGTH = 1;

export const MAX_DEVICE_NAME_LENGTH = 64;
export const MAX_PLATFORM_LENGTH = 32;
export const MAX_PUBLIC_KEY_LENGTH = 2048;

/**
 * Allowed barcode alphabet. Deliberately excludes whitespace, quotes,
 * semicolons, parentheses and back-ticks.
 */
export const BARCODE_PATTERN = /^[0-9A-Za-z][0-9A-Za-z._-]{0,63}$/;

/** Replay-prevention nonce (also used as the scan idempotency key). */
export const NONCE_PATTERN = /^[A-Za-z0-9_-]{8,64}$/;

/** Long-lived paired-device secret (base64url, generated by the desktop). */
export const CREDENTIAL_PATTERN = /^[A-Za-z0-9_-]{20,200}$/;

/** Single-use pairing ticket (base64url, generated by the desktop). */
export const TICKET_PATTERN = /^[A-Za-z0-9_-]{20,200}$/;

/** Device id (opaque, desktop-generated). */
export const DEVICE_ID_PATTERN = /^[A-Za-z0-9_-]{8,64}$/;

/** SHA-256 fingerprint of the desktop leaf certificate (lowercase hex, 64 chars). */
export const FINGERPRINT_PATTERN = /^[0-9a-f]{64}$/;

/** Accepted clock skew, in milliseconds, in both directions. */
export const TIMESTAMP_TOLERANCE_MS = 60_000;

/** Message types understood by the protocol (both directions). */
export const MESSAGE_TYPES = {
  HELLO: 'hello', // client → desktop : announce identity / credential
  SERVER_HELLO: 'server.hello', // desktop → client : challenge + hub metadata
  PAIR_REQUEST: 'pair.request', // client → desktop : redeem a pairing ticket
  PAIR_PENDING: 'pair.pending', // desktop → client : awaiting desktop approval
  PAIR_RESULT: 'pair.result', // desktop → client : credential issued / denied
  SCAN: 'scan', // client → desktop : a single barcode
  ACK: 'ack', // desktop → client : scan received by the gateway
  SCAN_RESULT: 'scan.result', // desktop → client : POS processing outcome
  ERROR: 'error', // desktop → client : rejection reason
  PING: 'ping', // client → desktop : keepalive
  PONG: 'pong', // desktop → client : keepalive reply
} as const;

export type MessageType = (typeof MESSAGE_TYPES)[keyof typeof MESSAGE_TYPES];

/** Whitelist of client → desktop types (mirrors the desktop whitelist). */
export const CLIENT_MESSAGE_TYPES: ReadonlySet<string> = new Set<string>([
  MESSAGE_TYPES.HELLO,
  MESSAGE_TYPES.PAIR_REQUEST,
  MESSAGE_TYPES.SCAN,
  MESSAGE_TYPES.PING,
]);

/**
 * Outcomes the desktop reports once the POS has ACTUALLY processed a scan.
 *
 * An `ack` only means the gateway accepted the frame; the cart outcome is only
 * known here. The phone must never claim a product was added on an `ack` alone.
 */
export const SCAN_OUTCOMES = {
  /** A product matched and was added to (or merged into) the cart. */
  ADDED: 'added',
  /** A `*qty` / calculation entry was applied instead of a product lookup. */
  QUANTITY: 'quantity',
  /** No product matches this barcode — nothing was created or changed. */
  UNKNOWN_PRODUCT: 'unknown_product',
  /** The product exists but its batch/expiry rules blocked the sale. */
  EXPIRED: 'expired',
  /** The scan matched nothing actionable on the desktop. */
  IGNORED: 'ignored',
} as const;

export type ScanOutcome = (typeof SCAN_OUTCOMES)[keyof typeof SCAN_OUTCOMES];

const SCAN_OUTCOME_VALUES: ReadonlySet<string> = new Set<string>(Object.values(SCAN_OUTCOMES));

/* ------------------------------------------------------------------ *
 * Result helpers (same shape as the desktop accept()/reject())
 * ------------------------------------------------------------------ */

export type Accepted<T> = { ok: true; value: T };
export type Rejected = { ok: false; code: string; reason: string };
export type Validated<T> = Accepted<T> | Rejected;

export function accept<T>(value: T): Accepted<T> {
  return { ok: true, value };
}

export function reject(code: string, reason: string): Rejected {
  return { ok: false, code, reason };
}

/* ------------------------------------------------------------------ *
 * Field validators (client-side sanity checks before sending)
 * ------------------------------------------------------------------ */

export function validateBarcode(value: unknown): Validated<string> {
  if (typeof value !== 'string') return reject('invalid_barcode', 'Barcode must be a string');
  const code = value.trim();
  if (code.length < MIN_BARCODE_LENGTH || code.length > MAX_BARCODE_LENGTH) {
    return reject('invalid_barcode_length', `Barcode must be ${MIN_BARCODE_LENGTH}-${MAX_BARCODE_LENGTH} characters`);
  }
  if (!BARCODE_PATTERN.test(code)) {
    return reject('invalid_barcode_format', 'Barcode contains unsupported characters');
  }
  return accept(code);
}

export function validateNonce(value: unknown): Validated<string> {
  if (typeof value !== 'string' || !NONCE_PATTERN.test(value)) {
    return reject('invalid_nonce', 'Nonce must be 8-64 URL-safe characters');
  }
  return accept(value);
}

export function validateCredential(value: unknown): Validated<string> {
  if (typeof value !== 'string' || !CREDENTIAL_PATTERN.test(value)) {
    return reject('invalid_credential', 'Credential is missing or malformed');
  }
  return accept(value);
}

export function validateDeviceId(value: unknown): Validated<string> {
  if (typeof value !== 'string' || !DEVICE_ID_PATTERN.test(value)) {
    return reject('invalid_device_id', 'Device id is missing or malformed');
  }
  return accept(value);
}

export function validateTicket(value: unknown): Validated<string> {
  if (typeof value !== 'string' || !TICKET_PATTERN.test(value)) {
    return reject('invalid_ticket', 'Pairing ticket is missing or malformed');
  }
  return accept(value);
}

function validateShortText(
  value: unknown,
  max: number,
  code: string,
  label: string,
  required = true,
): Validated<string | null> {
  if (value === undefined || value === null || value === '') {
    if (required) return reject(code, `${label} is required`);
    return accept(null);
  }
  if (typeof value !== 'string') return reject(code, `${label} must be a string`);
  const text = value.trim();
  if (text.length === 0 || text.length > max) return reject(code, `${label} must be 1-${max} characters`);
  // Reject control characters outright.
  if (/[\u0000-\u001F\u007F]/.test(text)) return reject(code, `${label} contains control characters`);
  return accept(text);
}

/* ------------------------------------------------------------------ *
 * Outgoing message builders (client → desktop)
 * ------------------------------------------------------------------ */

const encoder = new TextEncoder();

/** UTF-8 byte length, matching the desktop's MAX_FRAME_BYTES guard. */
export function frameByteLength(text: string): number {
  return encoder.encode(text).length;
}

export function encodeMessage(message: Record<string, unknown>): string {
  return JSON.stringify({ v: PROTOCOL_VERSION, ...message });
}

/**
 * Build a frame, refusing to produce one that would exceed the desktop's
 * hard frame ceiling.
 */
export function encodeFrame(message: Record<string, unknown>): string {
  const frame = encodeMessage(message);
  if (frameByteLength(frame) > MAX_FRAME_BYTES) {
    throw new Error('Frame exceeds the protocol maximum size');
  }
  return frame;
}

export function buildHello({ deviceId, credential }: { deviceId: string; credential: string }): string {
  return encodeFrame({ type: MESSAGE_TYPES.HELLO, deviceId, credential });
}

export function buildPairRequest({
  ticket,
  deviceName,
  platform,
  publicKey = null,
  replaceDeviceId = null,
  ts = Date.now(),
}: {
  ticket: string;
  deviceName: string;
  platform: string;
  publicKey?: string | null;
  /**
   * Previously issued device id for THIS phone, when re-pairing. The desktop
   * revokes it in the same transaction that issues the new credential, so an
   * intentional re-pair never leaves a duplicate device record behind.
   */
  replaceDeviceId?: string | null;
  ts?: number;
}): string {
  return encodeFrame({
    type: MESSAGE_TYPES.PAIR_REQUEST,
    ticket,
    deviceName,
    platform,
    publicKey,
    replaceDeviceId,
    ts,
  });
}

export function buildScan({
  deviceId,
  credential,
  nonce,
  code,
  ts = Date.now(),
}: {
  deviceId: string;
  credential: string;
  nonce: string;
  code: string;
  ts?: number;
}): string {
  return encodeFrame({
    type: MESSAGE_TYPES.SCAN,
    deviceId,
    credential,
    nonce,
    ts,
    code,
  });
}

export function buildPing(ts: number = Date.now()): string {
  return encodeFrame({ type: MESSAGE_TYPES.PING, ts });
}

/* ------------------------------------------------------------------ *
 * Incoming message parsing (desktop → client)
 * ------------------------------------------------------------------ */

export interface ServerHelloMessage {
  type: typeof MESSAGE_TYPES.SERVER_HELLO;
  fingerprint: string;
  requiresPairing: boolean;
  deviceName: string | null;
}

export interface PairPendingMessage {
  type: typeof MESSAGE_TYPES.PAIR_PENDING;
  requestId: string;
  expiresAt: number;
}

export interface PairResultMessage {
  type: typeof MESSAGE_TYPES.PAIR_RESULT;
  ok: boolean;
  deviceId: string | null;
  credential: string | null;
  reason: string | null;
}

export interface AckMessage {
  type: typeof MESSAGE_TYPES.ACK;
  nonce: string;
  /** `null` means the frame was a duplicate and was acknowledged but discarded. */
  scanId: string | null;
}

export interface ScanResultMessage {
  type: typeof MESSAGE_TYPES.SCAN_RESULT;
  nonce: string;
  /** What the POS actually did with the barcode (never inferred from an ack). */
  outcome: ScanOutcome;
  detail: string | null;
}

export interface ErrorMessage {
  type: typeof MESSAGE_TYPES.ERROR;
  code: string;
  reason: string;
  /**
   * Echo of the nonce of the rejected frame, when the desktop could read it.
   * Lets the phone attribute a rejection to the exact scan it sent instead of
   * waiting for the ack timeout.
   */
  nonce: string | null;
}

export interface PongMessage {
  type: typeof MESSAGE_TYPES.PONG;
  ts: number;
}

export type IncomingMessage =
  | ServerHelloMessage
  | PairPendingMessage
  | PairResultMessage
  | AckMessage
  | ScanResultMessage
  | ErrorMessage
  | PongMessage;

export type DecodedIncoming = { ok: true; message: IncomingMessage } | Rejected;

function asString(value: unknown): string | null {
  return typeof value === 'string' ? value : null;
}

/**
 * Parse and validate a raw frame received from the desktop gateway.
 * Unknown/malformed shapes are rejected rather than trusted.
 */
export function decodeIncoming(raw: string, now: number = Date.now()): DecodedIncoming {
  if (typeof raw !== 'string') return reject('malformed_frame', 'Unsupported frame type');
  if (frameByteLength(raw) > MAX_FRAME_BYTES) return reject('frame_too_large', 'Frame exceeds maximum size');

  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return reject('invalid_json', 'Frame is not valid JSON');
  }

  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    return reject('malformed_message', 'Message must be a JSON object');
  }
  const obj = parsed as Record<string, unknown>;
  if (obj.v !== PROTOCOL_VERSION) {
    return reject('unsupported_version', `Unsupported protocol version (expected ${PROTOCOL_VERSION})`);
  }
  if (typeof obj.type !== 'string') {
    return reject('missing_type', 'Message type is required');
  }

  switch (obj.type) {
    case MESSAGE_TYPES.SERVER_HELLO: {
      const fingerprint = asString(obj.fingerprint);
      if (!fingerprint || !FINGERPRINT_PATTERN.test(fingerprint)) {
        return reject('invalid_fingerprint', 'Gateway fingerprint is missing or malformed');
      }
      return {
        ok: true,
        message: {
          type: MESSAGE_TYPES.SERVER_HELLO,
          fingerprint,
          requiresPairing: obj.requiresPairing === true,
          deviceName: asString(obj.deviceName),
        },
      };
    }
    case MESSAGE_TYPES.PAIR_PENDING: {
      const requestId = asString(obj.requestId);
      if (!requestId || typeof obj.expiresAt !== 'number') {
        return reject('malformed_message', 'pair.pending is missing fields');
      }
      return { ok: true, message: { type: MESSAGE_TYPES.PAIR_PENDING, requestId, expiresAt: obj.expiresAt } };
    }
    case MESSAGE_TYPES.PAIR_RESULT: {
      const ok = obj.ok === true;
      const deviceId = asString(obj.deviceId);
      const credential = asString(obj.credential);
      if (ok && (!deviceId || !credential)) {
        return reject('malformed_message', 'pair.result is missing issued credentials');
      }
      return {
        ok: true,
        message: {
          type: MESSAGE_TYPES.PAIR_RESULT,
          ok,
          deviceId,
          credential,
          reason: asString(obj.reason),
        },
      };
    }
    case MESSAGE_TYPES.ACK: {
      const nonce = asString(obj.nonce);
      if (!nonce) return reject('malformed_message', 'ack is missing a nonce');
      return { ok: true, message: { type: MESSAGE_TYPES.ACK, nonce, scanId: asString(obj.scanId) } };
    }
    case MESSAGE_TYPES.SCAN_RESULT: {
      const nonce = asString(obj.nonce);
      const outcome = asString(obj.outcome);
      if (!nonce || !outcome || !SCAN_OUTCOME_VALUES.has(outcome)) {
        return reject('malformed_message', 'scan.result is missing a valid nonce or outcome');
      }
      return {
        ok: true,
        message: {
          type: MESSAGE_TYPES.SCAN_RESULT,
          nonce,
          outcome: outcome as ScanOutcome,
          detail: asString(obj.detail),
        },
      };
    }
    case MESSAGE_TYPES.ERROR: {
      return {
        ok: true,
        message: {
          type: MESSAGE_TYPES.ERROR,
          code: asString(obj.code) || 'unknown_error',
          reason: asString(obj.reason) || 'The gateway rejected the request',
          nonce: asString(obj.nonce),
        },
      };
    }
    case MESSAGE_TYPES.PONG: {
      if (typeof obj.ts !== 'number') return reject('malformed_message', 'pong is missing a timestamp');
      return { ok: true, message: { type: MESSAGE_TYPES.PONG, ts: obj.ts } };
    }
    default:
      return reject('unsupported_type', `Unsupported message type: ${obj.type}`);
  }
}

