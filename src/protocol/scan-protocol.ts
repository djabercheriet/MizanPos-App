/* ------------------------------------------------------------------ *
 * Logging safety
 * ------------------------------------------------------------------ */

const SENSITIVE_FIELDS = ['credential', 'ticket', 'publicKey', 'key', 'secret'];

/** Return a shallow copy with sensitive fields masked, for safe logging. */
export function redact<T extends Record<string, unknown>>(message: T): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(message)) {
    out[key] = SENSITIVE_FIELDS.includes(key) && value ? '[redacted]' : value;
  }
  return out;
}
