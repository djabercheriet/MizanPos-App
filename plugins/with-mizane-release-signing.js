const { createRunOncePlugin, withAppBuildGradle } = require('@expo/config-plugins');

const PLUGIN_NAME = 'with-mizane-release-signing';
const PLUGIN_VERSION = '1.0.0';

/**
 * Marker written into android/app/build.gradle. Its presence means the release
 * signing configuration has already been applied, which keeps the modification
 * idempotent when prebuild runs without --clean.
 */
const MARKER = '// @generated by with-mizane-release-signing';

/**
 * Injected before the `android { }` block. Resolves the four MIZANE_UPLOAD_*
 * Gradle properties and refuses to run a release task when any of them, or the
 * keystore itself, is missing - so a release can never be signed with the debug
 * keystore by accident.
 */
const SIGNING_PREAMBLE = [
  MARKER,
  '/**',
  ' * Release (upload) signing.',
  ' *',
  ' * The keystore and its credentials are injected through Gradle properties so',
  ' * that no secret is ever committed to the repository. Supply them in',
  ' * `~/.gradle/gradle.properties` (preferred), in the untracked',
  ' * `android/gradle.properties`, or with `-P` on the command line:',
  ' *',
  ' *   MIZANE_UPLOAD_STORE_FILE=release.keystore',
  ' *   MIZANE_UPLOAD_KEY_ALIAS=mizane',
  ' *   MIZANE_UPLOAD_STORE_PASSWORD=********',
  ' *   MIZANE_UPLOAD_KEY_PASSWORD=********',
  ' *',
  ' * `MIZANE_UPLOAD_STORE_FILE` is resolved relative to this module (android/app),',
  ' * so a bare file name points at `android/app/release.keystore`.',
  ' */',
  'def releaseSigningValue = { String name ->',
  '    def raw = project.findProperty(name)',
  '    if (raw == null) return null',
  '    def value = raw.toString().trim()',
  '    return value.isEmpty() ? null : value',
  '}',
  '',
  "def releaseStoreFile = releaseSigningValue('MIZANE_UPLOAD_STORE_FILE')",
  "def releaseKeyAlias = releaseSigningValue('MIZANE_UPLOAD_KEY_ALIAS')",
  "def releaseStorePassword = releaseSigningValue('MIZANE_UPLOAD_STORE_PASSWORD')",
  "def releaseKeyPassword = releaseSigningValue('MIZANE_UPLOAD_KEY_PASSWORD')",
  '',
  'def missingReleaseSigningProperties = [',
  "        'MIZANE_UPLOAD_STORE_FILE'    : releaseStoreFile,",
  "        'MIZANE_UPLOAD_KEY_ALIAS'     : releaseKeyAlias,",
  "        'MIZANE_UPLOAD_STORE_PASSWORD': releaseStorePassword,",
  "        'MIZANE_UPLOAD_KEY_PASSWORD'  : releaseKeyPassword,",
  '].findAll { name, value -> value == null }.keySet()',
  '',
  '/**',
  ' * Fail with an explicit message when a release task is about to run without the',
  ' * signing properties, rather than silently signing the release with the debug',
  ' * keystore. Debug-only invocations are unaffected: AGP names variant tasks after',
  ' * the build type, so only tasks ending in `Release` (assembleRelease,',
  ' * bundleRelease, installRelease, ...) are matched.',
  ' */',
  'gradle.taskGraph.whenReady { taskGraph ->',
  '    def runsReleaseTask = taskGraph.allTasks.any { task ->',
  "        task.project == project && task.name.endsWith('Release')",
  '    }',
  '    if (!runsReleaseTask) return',
  '',
  '    if (!missingReleaseSigningProperties.isEmpty()) {',
  '        throw new GradleException(',
  "                'Release signing is not configured. Missing Gradle propert' +",
  "                        (missingReleaseSigningProperties.size() == 1 ? 'y: ' : 'ies: ') +",
  "                        missingReleaseSigningProperties.join(', ') +",
  "                        '. Set them in ~/.gradle/gradle.properties or pass them with -P, ' +",
  "                        'then retry. Refusing to sign the release with the debug keystore.'",
  '        )',
  '    }',
  '',
  '    def keystore = project.file(releaseStoreFile)',
  '    if (!keystore.exists()) {',
  '        throw new GradleException(',
  '                "Release signing keystore not found: ${keystore.absolutePath} " +',
  "                        \"(MIZANE_UPLOAD_STORE_FILE='${releaseStoreFile}'). The path is resolved \" +",
  "                        'relative to the android/app module.'",
  '        )',
  '    }',
  '}',
  '',
  '',
].join('\n');

/**
 * Injected as the last entry of the existing `signingConfigs { }` block.
 * Values are only assigned when present so that configuring a debug build never
 * fails; a release build without them is stopped by the taskGraph guard above.
 */
const SIGNING_CONFIG = [
  '        release {',
  '            // Values are read from the MIZANE_UPLOAD_* Gradle properties resolved',
  '            // above. They are only assigned when present so that configuring a',
  '            // debug build never fails; a release build without them is stopped',
  '            // by the `gradle.taskGraph.whenReady` guard.',
  '            if (releaseStoreFile != null) {',
  '                storeFile file(releaseStoreFile)',
  '            }',
  '            if (releaseStorePassword != null) {',
  '                storePassword releaseStorePassword',
  '            }',
  '            if (releaseKeyAlias != null) {',
  '                keyAlias releaseKeyAlias',
  '            }',
  '            if (releaseKeyPassword != null) {',
  '                keyPassword releaseKeyPassword',
  '            }',
  '        }',
  '',
].join('\n');

/**
 * Replaces the React Native template's "generate your own keystore" note so the
 * generated file documents where the credentials actually come from.
 */
const TEMPLATE_CAUTION_COMMENT = [
  "            // Caution! In production, you need to generate your own keystore file.",
  '            // see https://reactnative.dev/docs/signed-apk-android.',
  '',
].join('\n');

const MIZANE_RELEASE_COMMENT = [
  '            // Signed with the upload keystore from the MIZANE_UPLOAD_* Gradle',
  '            // properties. Never falls back to the debug keystore: see the',
  '            // `gradle.taskGraph.whenReady` guard at the top of this file.',
  '            // See https://reactnative.dev/docs/signed-apk-android.',
  '',
].join('\n');

const RELEASE_SIGNING_CONFIG_REFERENCE = 'signingConfig signingConfigs.debug';
const RELEASE_SIGNING_CONFIG_REPLACEMENT = 'signingConfig signingConfigs.release';

/**
 * Returns the index of the `}` that closes the block opened at `openBraceIndex`,
 * or -1 when the braces are unbalanced.
 */
function findBlockEnd(source, openBraceIndex) {
  let depth = 0;
  for (let index = openBraceIndex; index < source.length; index += 1) {
    const character = source[index];
    if (character === '{') {
      depth += 1;
    } else if (character === '}') {
      depth -= 1;
      if (depth === 0) {
        return index;
      }
    }
  }
  return -1;
}

function requireBlock(source, declaration, file) {
  const declarationIndex = source.indexOf(declaration);
  if (declarationIndex === -1) {
    throw new Error(
      `${PLUGIN_NAME}: could not find "${declaration.trim()}" in ${file}. ` +
        'The React Native template may have changed; refusing to patch it blindly.'
    );
  }
  const openBraceIndex = source.indexOf('{', declarationIndex);
  const closeBraceIndex = findBlockEnd(source, openBraceIndex);
  if (openBraceIndex === -1 || closeBraceIndex === -1) {
    throw new Error(
      `${PLUGIN_NAME}: unbalanced braces after "${declaration.trim()}" in ${file}.`
    );
  }
  return { openBraceIndex, closeBraceIndex };
}

/**
 * Points buildTypes.release at the release keystore instead of the debug one.
 * Only the release variant is touched.
 */
function useReleaseSigningInReleaseBuildType(source, file) {
  const buildTypes = requireBlock(source, 'buildTypes {', file);
  const buildTypesBody = source.slice(buildTypes.openBraceIndex, buildTypes.closeBraceIndex);

  const release = requireBlock(buildTypesBody, 'release {', file);
  const releaseBody = buildTypesBody.slice(release.openBraceIndex, release.closeBraceIndex);

  if (!releaseBody.includes(RELEASE_SIGNING_CONFIG_REFERENCE)) {
    throw new Error(
      `${PLUGIN_NAME}: the release build type in ${file} does not reference the debug ` +
        'signing config, so it cannot be repointed safely.'
    );
  }

  const patchedReleaseBody = releaseBody.replace(
    RELEASE_SIGNING_CONFIG_REFERENCE,
    RELEASE_SIGNING_CONFIG_REPLACEMENT
  );

  return (
    source.slice(0, buildTypes.openBraceIndex) +
    buildTypesBody.replace(releaseBody, patchedReleaseBody) +
    source.slice(buildTypes.closeBraceIndex)
  );
}

function applyReleaseSigning(contents, file) {
  if (contents.includes(MARKER)) {
    return contents;
  }

  const androidBlockIndex = contents.indexOf('android {');
  if (androidBlockIndex === -1) {
    throw new Error(`${PLUGIN_NAME}: could not find the "android {" block in ${file}.`);
  }

  let patched =
    contents.slice(0, androidBlockIndex) +
    SIGNING_PREAMBLE +
    contents.slice(androidBlockIndex);

  const signingConfigs = requireBlock(patched, 'signingConfigs {', file);
  // Insert at the start of the line that holds the closing brace, so the brace
  // keeps its own indentation instead of being absorbed by the inserted block.
  const closingLineStart = patched.lastIndexOf('\n', signingConfigs.closeBraceIndex) + 1;
  patched =
    patched.slice(0, closingLineStart) + SIGNING_CONFIG + patched.slice(closingLineStart);

  patched = patched.replace(TEMPLATE_CAUTION_COMMENT, MIZANE_RELEASE_COMMENT);
  patched = useReleaseSigningInReleaseBuildType(patched, file);

  return patched;
}

module.exports = createRunOncePlugin(
  (config) =>
    withAppBuildGradle(config, (config) => {
      const file = 'android/app/build.gradle';
      if (config.modResults.language !== 'groovy') {
        throw new Error(`${PLUGIN_NAME}: unexpected ${file} language (${config.modResults.language}).`);
      }
      config.modResults.contents = applyReleaseSigning(config.modResults.contents, file);
      return config;
    }),
  PLUGIN_NAME,
  PLUGIN_VERSION
);
